import { chromium } from 'playwright-core'
const executablePath = '/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome'
const base = 'https://afribok.vertexsautomations.com'
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--use-file-for-fake-audio-capture=/tmp/afribok-live/consult.wav'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, baseURL: base, permissions: ['microphone'] })
const page = await context.newPage()
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text()))
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
page.on('requestfailed', (r) => console.log('REQFAIL', r.url(), r.failure()?.errorText))
page.on('response', (r) => { if (r.url().includes('/api/ai/')) console.log('RESP', r.status(), r.url()) })
await page.goto('/login', { waitUntil: 'networkidle' })
await page.fill('#email', 'nurse@afribok.health')
await page.fill('#password', 'Afribok#2026')
await page.click('.auth-submit')
await page.waitForURL('**/app', { timeout: 20000 })
await page.goto('/app/visits', { waitUntil: 'networkidle' })
await page.waitForTimeout(1000)
await page.locator('.visit-row').filter({ hasText: /Waiting/i }).first().locator('a.row-link').click()
await page.waitForTimeout(1200)
console.log('mic support', await page.evaluate(() => ({ recorder: typeof MediaRecorder, gUM: Boolean(navigator.mediaDevices?.getUserMedia), AudioCtx: typeof AudioContext })))
await page.getByRole('button', { name: /record consultation|record another note/i }).first().click()
await page.waitForTimeout(6000)
console.log('after start:', (await page.locator('.scribe-controls').innerText()).replaceAll('\n',' | '))
await page.getByRole('button', { name: /stop & draft note/i }).first().click()
await page.waitForTimeout(20000)
console.log('notice:', await page.locator('.clinical-panel .notice').allInnerTexts())
console.log('body has note:', await page.locator('.note-section').count())
await page.screenshot({ path: '/tmp/afribok-live/shots/scribe-debug.png', fullPage: false })
await browser.close()
