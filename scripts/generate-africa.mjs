import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { merge } from 'topojson-client'

const AFRICA = new Set([
  'Algeria', 'Angola', 'Benin', 'Botswana', 'Burkina Faso', 'Burundi', 'Cameroon',
  "Côte d'Ivoire", 'Central African Rep.', 'Chad', 'Congo', 'Dem. Rep. Congo',
  'Djibouti', 'Egypt', 'Eq. Guinea', 'Eritrea', 'eSwatini', 'Ethiopia', 'Gabon',
  'Gambia', 'Ghana', 'Guinea', 'Guinea-Bissau', 'Kenya', 'Lesotho', 'Liberia',
  'Libya', 'Madagascar', 'Malawi', 'Mali', 'Mauritania', 'Morocco', 'Mozambique',
  'Namibia', 'Niger', 'Nigeria', 'Rwanda', 'Senegal', 'Sierra Leone', 'Somalia',
  'Somaliland', 'South Africa', 'S. Sudan', 'Sudan', 'Tanzania', 'Togo', 'Tunisia',
  'Uganda', 'W. Sahara', 'Zambia', 'Zimbabwe',
])

const world = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)))
const geometries = world.objects.countries.geometries.filter((g) => AFRICA.has(g.properties.name))
const merged = merge(world, geometries)

const project = ([lon, lat]) => {
  // Web Mercator keeps the continent's familiar map silhouette.
  const clamped = Math.max(-84, Math.min(84, lat))
  const y = Math.log(Math.tan(Math.PI / 4 + (clamped * Math.PI) / 360))
  return [lon, y]
}

const rings = []
for (const polygon of merged.coordinates) {
  for (const ring of polygon) {
    if (ring.length > 8) rings.push(ring.map(project))
  }
}

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity
for (const ring of rings) {
  for (const [x, y] of ring) {
    if (x < minX) minX = x
    if (x > maxX) maxX = x
    if (y < minY) minY = y
    if (y > maxY) maxY = y
  }
}

const WIDTH = 100
const HEIGHT = 118
const PAD = 2
const scale = Math.min((WIDTH - PAD * 2) / (maxX - minX), (HEIGHT - PAD * 2) / (maxY - minY))
const offsetX = (WIDTH - (maxX - minX) * scale) / 2
const offsetY = (HEIGHT - (maxY - minY) * scale) / 2

const toPath = (ring) =>
  ring
    .map(([x, y], i) => {
      const px = offsetX + (x - minX) * scale
      const py = HEIGHT - (offsetY + (y - minY) * scale)
      return `${i === 0 ? 'M' : 'L'}${px.toFixed(2)} ${py.toFixed(2)}`
    })
    .join('') + 'Z'

// Keep the largest rings so the SVG stays lightweight.
const sorted = rings.sort((a, b) => b.length - a.length).slice(0, 18)
const path = sorted.map(toPath).join('')

mkdirSync(new URL('../src/data', import.meta.url), { recursive: true })
const out = `// Generated by scripts/generate-africa.mjs from Natural Earth 1:50m data.\nexport const AFRICA_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}'\nexport const AFRICA_PATH =\n  '${path}'\n`
writeFileSync(new URL('../src/data/africa.ts', import.meta.url), out)
console.log(`Africa outline: ${sorted.length} rings, ${path.length} chars, viewBox ${WIDTH}x${HEIGHT}`)
